/**
 * Concatenates rather than overwrites, so a spelling shared across regions
 * offers every reading as an alternative: "ha" is both ハ (Korean) and ハー
 * (Vietnamese), "li" both リー (Chinese) and リ (Japanese).
 */
function merge(
  groups: Array<Record<string, LatinNameEntry[]>>,
): Record<string, LatinNameEntry[]> {
  const out: Record<string, LatinNameEntry[]> = {}
  for (const group of groups) {
    for (const [key, entries] of Object.entries(group)) {
      const existing = (out[key] ??= [])
      for (const entry of entries) {
        const duplicate = existing.some(
          (e) => e.kana === entry.kana && e.origin === entry.origin,
        )
        if (!duplicate) existing.push(entry)
      }
    }
  }
  return out
}

